<?php

namespace Azera\Aop;

/**
 * Process-wide runtime shared by generated proxy classes and {@see ProxyFactory}.
 *
 * Generated proxies are written to disk and may be loaded in a process that never ran
 * the factory that emitted them, so advice instances cannot be embedded in the generated
 * source. Instead, on first invocation each proxy asks this registry for its plan; the
 * plan is built once per (namespace, class, method) from the registered interceptors and
 * the method's advice attributes, then memoized for the rest of the process.
 *
 * **Namespacing.** More than one factory (two {@see AppContext} instances, a test
 * harness plus the application) can live in one process, and each has its own
 * interceptor instances. A single global map meant the last publisher silently
 * replaced the others, so proxies generated by the first factory began resolving
 * plans against the second factory's interceptors. Every registration therefore
 * carries a namespace that the generated proxy bakes into its source. The factory
 * derives it from its cache directory, so it is stable across processes (a cached
 * proxy file keeps resolving in the process that loads it later) and distinct
 * between factories that use different directories.
 *
 * Standalone use must publish via {@see self::setInterceptors()} (or
 * `ProxyFactory::publish()`) before invoking a generated proxy.
 *
 * @internal Not part of the public API.
 */
final class AopRuntime
{
    /** @var array<string, array<class-string<Advice>, InterceptorInterface>> namespace => advice class => interceptor */
    private static array $interceptors = [];

    /** @var array<string, array<string, AopPlan>> namespace => (class::method) => plan */
    private static array $plans = [];

    /**
     * Replace every interceptor for one namespace.
     *
     * Plans for that namespace are discarded: they captured the interceptor
     * instances that were registered when they were built.
     *
     * @param array<class-string<Advice>, InterceptorInterface> $interceptors
     */
    public static function setInterceptors(string $namespace, array $interceptors): void
    {
        self::$interceptors[$namespace] = $interceptors;
        self::clearPlans($namespace);
    }

    /**
     * Register (or replace) one interceptor for a namespace without touching the rest.
     *
     * @param class-string<Advice> $adviceClass
     */
    public static function setInterceptor(
        string $namespace,
        string $adviceClass,
        InterceptorInterface $interceptor,
    ): void {
        self::$interceptors[$namespace][$adviceClass] = $interceptor;
        self::clearPlans($namespace);
    }

    /**
     * Forget every memoized plan for one namespace.
     *
     * Called when the interceptor map changes: a plan captures the interceptor
     * instances that were registered when it was built, so a plan that survived a
     * re-registration would keep invoking the old interceptor for an existing
     * advised method.
     */
    public static function clearPlans(string $namespace): void
    {
        unset(self::$plans[$namespace]);
    }

    /**
     * Resolve (and memoize) the plan for one advised method in one namespace.
     *
     * @param list<class-string<Advice>> $adviceClasses Advices declared on the method, outermost first.
     */
    public static function plan(string $namespace, string $class, string $method, array $adviceClasses): AopPlan
    {
        $key = $class . '::' . $method;

        return self::$plans[$namespace][$key] ??= self::build($namespace, $key, $class, $method, $adviceClasses);
    }

    /**
     * @param list<class-string<Advice>> $adviceClasses
     */
    private static function build(
        string $namespace,
        string $key,
        string $class,
        string $method,
        array $adviceClasses,
    ): AopPlan {
        $interceptors = self::$interceptors[$namespace] ?? [];
        $chain        = [];
        $advice       = [];

        if ($adviceClasses !== []) {
            $ref = new \ReflectionMethod($class, $method);

            foreach ($adviceClasses as $adviceClass) {
                if (!isset($interceptors[$adviceClass])) {
                    throw new \LogicException(
                        "No interceptor registered for advice [{$adviceClass}] on {$key} (namespace '{$namespace}'). "
                        . 'Register one via AppContext::registerInterceptor() / ProxyFactory::register() before the advised method is called.'
                    );
                }

                $chain[]  = $interceptors[$adviceClass];
                $instance = null;
                foreach ($ref->getAttributes($adviceClass) as $attribute) {
                    $instance = $attribute->newInstance();
                    break;
                }
                if ($instance !== null) {
                    $advice[$adviceClass] = $instance;
                }
            }
        }

        return new AopPlan(new Pipeline($chain), $advice, self::parameterNames($class, $method));
    }

    /** @return list<string> */
    private static function parameterNames(string $class, string $method): array
    {
        try {
            return array_map(
                static fn(\ReflectionParameter $p): string => $p->getName(),
                (new \ReflectionMethod($class, $method))->getParameters(),
            );
        } catch (\ReflectionException) {
            return [];
        }
    }
}
